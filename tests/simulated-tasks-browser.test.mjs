import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { setTimeout as delay } from 'node:timers/promises';
import { chromium } from 'playwright-core';
import { createApp } from '../server.mjs';
import { simulationPlanner } from '../examples/simulation-fixture.mjs';

const until = async check => { for (let i = 0; i < 1000; i++) { if (check()) return; await delay(10); } throw new Error('模拟页面状态等待超时'); };
test('真实Edge页面确认计划、模拟失败重试、暂停/继续、刷新及人工确认；桌面和窄屏', { timeout: 60000 }, async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'taskflow-sim-browser-'));
  const app = await createApp({ dataDir: directory, stepDelayMs: 0, planner: simulationPlanner });
  let browser;
  t.after(async () => { await browser?.close(); await app.close(); await rm(directory, { recursive: true, force: true }); });
  const project = await app.store.create({ name: 'A-B/C-D-E 模拟演示', source: { filename: 'demo.md', content: 'A完成后B和C并行；D确认后才执行E。' } });
  const plan = await app.orchestrator.createRun(project.id);
  await until(() => plan.status === 'awaiting_spec');
  await app.orchestrator.action(project.id, plan.id, { action: 'approve_spec', revision: plan.specRevision });
  await until(() => plan.status === 'awaiting_review');
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  page.on('console', entry => { if (entry.type() === 'error') errors.push(entry.text()); });
  await page.goto(`http://127.0.0.1:${app.server.address().port}/?view=details`);
  await page.getByRole('button', { name: '确认计划并导出', exact: true }).click();
  await until(() => plan.status === 'succeeded');
  await page.getByRole('tab', { name: /开发任务/ }).click();
  await page.locator('#simulation-tools').evaluate(element => { element.open = true; });
  await page.getByRole('button', { name: '启动模拟编排', exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('[data-simulation-action="start"]').disabled);
  await page.getByLabel('模拟时长', { exact: true }).fill('800');
  await page.getByLabel('首次失败任务 ID', { exact: true }).fill('B');
  await page.getByRole('button', { name: '启动模拟编排', exact: true }).click();
  const current = () => app.simulationService.list(project.id, plan.id).at(-1);
  await until(() => current()?.tasks.filter(task => task.status === 'running').length === 2);
  await page.getByRole('button', { name: '阶段边界暂停', exact: true }).click();
  await until(() => current()?.status === 'paused' && current().tasks.every(task => task.status !== 'running'));
  assert.equal(current().tasks.find(task => task.id === 'D').attempts.length, 0);
  await page.getByRole('button', { name: '继续模拟', exact: true }).click();
  await until(() => current()?.status === 'failed');
  await page.locator('.dev-task[data-task="B"]').click();
  await page.getByRole('button', { name: '重试此模拟任务', exact: true }).click();
  await until(() => current()?.status === 'awaiting_confirmation');
  const id = current().id;
  await page.reload(); await page.getByRole('tab', { name: /开发任务/ }).click();
  await page.locator('#simulation-tools').evaluate(element => { element.open = true; });
  await page.locator('.dev-task[data-task="D"]').click();
  await page.getByRole('button', { name: '确认此模拟结果', exact: true }).waitFor();
  assert.equal(current().tasks.find(task => task.id === 'E').attempts.length, 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('模拟人工确认依据', { exact: true }).fill('核对模拟结果及依赖后，确认继续。');
  await delay(900);
  assert.equal(await page.getByLabel('模拟人工确认依据', { exact: true }).inputValue(), '核对模拟结果及依赖后，确认继续。');
  await page.getByRole('button', { name: '确认此模拟结果', exact: true }).click();
  await until(() => current()?.status === 'completed');
  await page.waitForFunction(() => document.querySelector('.dev-task[data-task="E"]')?.classList.contains('sim-completed'));
  assert.equal(current().id, id); assert.equal(current().realAcceptance, false);
  assert.equal(current().tasks.find(task => task.id === 'A').attempts.length, 1);
  assert.equal(current().tasks.find(task => task.id === 'C').attempts.length, 1);
  assert.equal(current().tasks.find(task => task.id === 'B').attempts.length, 2);
  assert.ok(await page.locator('#simulation-panel-host').innerText().then(text => text.includes('不代表真实编码')));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  const evidence = path.resolve('output/simulation-verification'); await mkdir(evidence, { recursive: true });
  await page.screenshot({ path: path.join(evidence, 'mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: path.join(evidence, 'desktop.png'), fullPage: true });
  assert.deepEqual(errors, []);
});
