import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright-core';
import { createApp } from '../server.mjs';

const roleIds = ['spec', 'engineering', 'verification', 'coding', 'review'];
const fixtureKey = 'browser-fixture-api-key-not-real';
const listen = server => new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
async function fixture(t) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'tf-agent-settings-browser-'));
  let app, browser;
  t.after(async () => {
    await browser?.close(); await app?.close();
    assert.equal(path.dirname(directory), os.tmpdir());
    await rm(directory, { recursive: true, force: true });
  });
  app = await createApp({ dataDir: directory, teamEnabled: false, executionService: null, agentEnvironment: {},
    verificationPlanningService: null, plannedExecutionService: null, sourceChangeService: null });
  await listen(app.server);
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const settings = async () => (await fetch(`${base}/api/agent-settings`)).json();
  return { app, browser, base, settings };
}
async function ready(page, base, kind) {
  await page.goto(`${base}/${kind === 'api' ? 'api' : 'agent'}-settings.html`);
  await page.locator(kind === 'api' ? '#api-services-section' : '#agent-settings-form').waitFor();
}
const dialog = page => page.getByRole('dialog');
const saveApi = async page => {
  await dialog(page).getByRole('button', { name: '保存并应用', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'API 服务已保存并应用' }).waitFor();
};
const saveRoles = async page => {
  await page.getByRole('button', { name: '保存并应用', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '角色分配已保存并应用' }).waitFor();
};
async function add(page, { name, url, model, key = '' }) {
  await page.getByRole('button', { name: '添加服务', exact: true }).click();
  await dialog(page).getByLabel('服务名称', { exact: true }).fill(name);
  await dialog(page).getByLabel('API 基础地址', { exact: true }).fill(url);
  await dialog(page).getByLabel('模型名称', { exact: true }).fill(model);
  if (key) await dialog(page).getByLabel('API 密钥', { exact: true }).fill(key);
}

