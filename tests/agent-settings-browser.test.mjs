  assert.ok(roleIds.every(role => snapshot.roles[role] === providerId));
  assert.equal(snapshot.providers[0].hasKey, true);
  assert.equal(snapshot.providers[0].jsonMode, false);
  assert.equal(snapshot.providers[0].thinking, 'disabled');
  assert.deepEqual(snapshot.providers[0].pricing, pricing);
