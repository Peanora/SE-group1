test('配置 CAS 冲突保留 API 抽屉密码及角色草稿，跨页保存不覆盖另一职责', { timeout: 60000 }, async t => {
  const { browser, base, settings } = await fixture(t);
  const first = await browser.newPage(), second = await browser.newPage();
  for (const page of [first, second]) {
    await ready(page, base, 'api');
    await add(page, { name: page === first ? '先保存' : '后保存草稿', url: 'https://model.invalid/v1', model: 'fixture-model', key: fixtureKey });
  }
  await saveApi(first);
  await dialog(second).getByRole('button', { name: '保存并应用', exact: true }).click();
  await dialog(second).getByRole('alert').filter({ hasText: '当前修改仍保留' }).waitFor();
  assert.equal(await dialog(second).getByLabel('服务名称', { exact: true }).inputValue(), '后保存草稿');
  assert.equal(await dialog(second).getByLabel('API 密钥', { exact: true }).inputValue(), fixtureKey);
  let snapshot = await settings();
  assert.equal(snapshot.providers.length, 1);
  assert.equal(snapshot.providers[0].name, '先保存');
  const providerId = snapshot.providers[0].id;
  second.once('dialog', dialog => dialog.accept());
  await ready(second, base, 'agents');
  assert.equal(await second.locator('input[type=password]').count(), 0, '导航到角色页不带去密钥输入');
  assert.ok(!(await second.content()).includes(fixtureKey));
  assert.deepEqual(await second.evaluate(() => [Object.keys(localStorage), Object.keys(sessionStorage)]), [[], []]);
  await first.getByRole('button', { name: '编辑 先保存', exact: true }).click();
  await dialog(first).getByLabel('服务名称', { exact: true }).fill('更新后的服务');
  await saveApi(first);
  await second.locator('[data-agent-role="review"]').selectOption(providerId);
  await second.getByRole('button', { name: '保存并应用', exact: true }).click();
  await second.getByRole('alert').filter({ hasText: '当前修改仍保留' }).waitFor();
  assert.equal(await second.locator('[data-agent-role="review"]').inputValue(), providerId);
  snapshot = await settings();
  assert.equal(snapshot.providers[0].name, '更新后的服务');
  assert.equal(snapshot.roles.review, 'env');
  second.once('dialog', dialog => dialog.accept());
  const reloaded = second.waitForResponse(response => response.url().endsWith('/api/agent-settings') && response.request().method() === 'GET');
  await second.getByRole('button', { name: '重新载入配置', exact: true }).click();
  await reloaded;
  await second.locator('[data-agent-role="review"]').selectOption(providerId);
  await first.getByRole('button', { name: '编辑 更新后的服务', exact: true }).click();
  await dialog(first).getByLabel('模型名称', { exact: true }).fill('新模型草稿');
  await dialog(first).getByLabel('API 密钥', { exact: true }).fill('replacement-fixture-key');
  await saveRoles(second);
  await dialog(first).getByRole('button', { name: '保存并应用', exact: true }).click();
  await dialog(first).getByRole('alert').filter({ hasText: '当前修改仍保留' }).waitFor();
  assert.equal(await dialog(first).getByLabel('模型名称', { exact: true }).inputValue(), '新模型草稿');
  assert.equal(await dialog(first).getByLabel('API 密钥', { exact: true }).inputValue(), 'replacement-fixture-key');
  snapshot = await settings();
  assert.equal(snapshot.providers[0].model, 'fixture-model');
  assert.equal(snapshot.roles.review, providerId);
  first.once('dialog', dialog => dialog.accept());
  await ready(first, base, 'agents');
  await first.goBack();
  await first.locator('#api-services-section').waitFor();
  assert.equal(await first.locator('#provider-key').inputValue(), '');
});

test('首次读取失败可重试，未保存角色导航可取消，长列表删除拒绝在当前服务旁可见', { timeout: 45000 }, async t => {
  const { browser, base, settings } = await fixture(t);
  const initial = await settings();
  const providers = Array.from({ length: 20 }, (_, index) => ({ id: `fixture-${index}`, name: `本机服务 ${index}`, baseUrl: `http://127.0.0.1:${5100 + index}/v1`, model: `fixture-model-${index}`, jsonMode: true, thinking: '' }));
  const seeded = await fetch(`${base}/api/agent-settings`, { method: 'PUT', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ revision: initial.revision, providers, roles: { ...initial.roles, review: providers.at(-1).id } }) });
  assert.equal(seeded.status, 200);
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  let writes = 0;
  page.on('request', request => { if (request.method() === 'PUT' && request.url().endsWith('/api/agent-settings')) writes++; });
  let firstGet = true;
  await page.route('**/api/agent-settings', route => {
    if (route.request().method() === 'GET' && firstGet) { firstGet = false; return route.fulfill({ status: 503, json: { error: '配置暂时不可用，请重试。' } }); }
    return route.continue();
  });
  await page.goto(`${base}/agent-settings.html`);
  await page.getByRole('alert').filter({ hasText: '配置暂时不可用' }).waitFor();
  assert.equal(await page.getByRole('button', { name: '重新载入配置', exact: true }).isEnabled(), true);
  await page.getByRole('button', { name: '重新载入配置', exact: true }).click();
  await page.locator('[data-agent-role="spec"]').selectOption(providers[0].id);
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('link', { name: 'API 服务', exact: true }).click();
  assert.equal(new URL(page.url()).pathname, '/agent-settings.html');
  assert.equal(await page.locator('[data-agent-role="spec"]').inputValue(), providers[0].id);
  assert.equal((await settings()).roles.spec, 'env');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: '重新载入配置', exact: true }).click();
  assert.equal(await page.locator('[data-agent-role="spec"]').inputValue(), providers[0].id);
  await page.locator('[data-agent-role="spec"]').selectOption('env');
  assert.match(await page.locator('#agent-settings-save-state').textContent(), /已应用配置版本/);
  await page.getByRole('link', { name: 'API 服务', exact: true }).click();
  const row = page.locator(`[data-provider-id="${providers.at(-1).id}"]`), remove = row.getByRole('button', { name: '删除 本机服务 19', exact: true });
  await remove.click();
  const error = row.getByRole('alert');
  await error.filter({ hasText: '请先在「Agent 角色」更换服务并保存' }).waitFor();
  const box = await error.boundingBox();
  assert.ok(box.y >= 0 && box.y + box.height <= 844, '删除拒绝在当前长列表操作位置可读');
  assert.equal(await remove.evaluate(element => element === document.activeElement), true, '拒绝不抢走当前按钮焦点');
  assert.equal((await settings()).providers.length, 20);
  page.once('dialog', dialog => { assert.match(dialog.message(), /本机服务 0/); return dialog.dismiss(); });
  await page.getByRole('button', { name: '删除 本机服务 0', exact: true }).click();
  assert.equal(writes, 0, '取消删除及绑定拒绝均不提交配置');
  assert.equal((await settings()).providers.length, 20);
});
